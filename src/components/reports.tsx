function ReportDetailWorkspace({ id }: { id: string }) {
  const user = useSession(),
    cache = useQueryClient();
  const key = ["reports", "detail", user.id, user.role, id];
  const [drafts, setDrafts] = useState<ReportSection[] | null>(null),
    [invalid, setInvalid] = useState<string>(),
    [notice, setNotice] = useState(""),
    [intent, setIntent] = useState<Action | null>(null),
    [customTitle, setCustomTitle] = useState(""),
    [customKind, setCustomKind] = useState("TEXT"),
    [saveToLibrary, setSaveToLibrary] = useState(false);
  const latestDraft = useRef<ReportSection[] | null>(null);
  const saving = useRef(false);
  const libraryWriting = useRef(false);
  const [autosavePaused, setAutosavePaused] = useState(false);
  const [savedAt, setSavedAt] = useState<string>();
  const [editorKeys, setEditorKeys] = useState<Record<string, string>>({});
  const clearDraft = () => {
    latestDraft.current = null;
    setDrafts(null);
    setAutosavePaused(false);
  };
  const query = useQuery({
    queryKey: key,
    staleTime: 0,
    queryFn: async () => {
      const report = parseReport(
        (await api<{ data: unknown }>(`/reports/${id}`)).data,
        user.role,
      );
      if (report.id !== id) throw new Error("Unexpected report");
      return report;
    },
  });
  const report = query.data,
    dirty = drafts !== null;
  const editable =
    report &&
    user.role === "COORDINATOR" &&
    report.author.id === user.id &&
    report.status === "DRAFT" &&
    !report.archivedAt;
  const sections = drafts ?? report?.sections ?? [];
  useEffect(() => {
    if (!dirty) return;
    const warn = (event: BeforeUnloadEvent) => {
      event.preventDefault();
      event.returnValue = "";
    };
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);
  const accept = async (result: Report, message: string) => {
    cache.setQueryData(key, result);
    clearDraft();
    setIntent(null);
    setNotice(message);
    await cache.invalidateQueries({ queryKey: ["reports", "list"] });
    await cache.invalidateQueries({ queryKey: ["sessions"] });
    await cache.invalidateQueries({ queryKey: ["dashboard"] });
  };
  const save = useMutation({
    mutationFn: async (snapshot: ReportSection[]) => {
      if (!editable) throw new Error("This report is no longer editable.");
      const result = parseReport(
        (
          await api<{ data: unknown }>(`/reports/${id}/sections`, {
            method: "PATCH",
            body: sectionPayload(snapshot),
          })
        ).data,
        user.role,
      );
      return validateSaveAcknowledgement(snapshot, result, id, user.id);
    },
    onSuccess: async (result, snapshot) => {
      setEditorKeys((previous) => {
        const next = { ...previous };
        snapshot.forEach((section, index) => {
          next[result.sections[index]!.id] = previous[section.id] ?? section.id;
        });
        return next;
      });
      const current = latestDraft.current;
      const next =
        current === snapshot || current === null
          ? null
          : rebaseReportDraft(snapshot, result.sections, current);
      latestDraft.current = next;
      setDrafts(next);
      cache.setQueryData(key, result);
      setAutosavePaused(false);
      setSavedAt(
        new Date().toLocaleTimeString([], {
          hour: "2-digit",
          minute: "2-digit",
        }),
      );
      setNotice(
        next
          ? "Earlier changes saved; newer edits are waiting to save."
          : "Report saved.",
      );
      await Promise.all([
        cache.invalidateQueries({ queryKey: ["reports", "list"] }),
        cache.invalidateQueries({ queryKey: ["sessions"] }),
      ]);
    },
    onError: () => setAutosavePaused(true),
    onSettled: () => {
      saving.current = false;
    },
  });
  const transition = useMutation({
    mutationFn: async (action: Action) => {
      if (dirty || !report || !canReportAction(report, user, action))
        throw new Error("This report action is no longer available.");
      const regenerate = action === "progress" || action === "highlights";
      const result = parseReport(
        (
          await api<{ data: unknown }>(
            `/reports/${id}/${regenerate ? "sections/regenerate" : action}`,
            { method: "POST", body: regenerate ? { key: action } : {} },
          )
        ).data,
        user.role,
      );
      const archival = action === "archive" || action === "unarchive";
      const expected = archival
        ? report.status
        : action === "confirm"
          ? "FINAL"
          : action === "send"
            ? "SENT"
            : "DRAFT";
      if (
        result.id !== id ||
        result.status !== expected ||
        (action === "takeover" && result.author.id !== user.id) ||
        (archival &&
          (result.author.id !== report.author.id ||
            result.version !== report.version ||
            (action === "archive"
              ? !result.archivedAt || result.openChangeRequests !== 0
              : result.archivedAt !== null)))
      )
        throw new Error("Unexpected report acknowledgement");
      return result;
    },
    onSuccess: (result, action) =>
      accept(
        result,
        action === "send"
          ? "Report sent to Sponsors."
          : action === "archive"
            ? "Report archived."
            : action === "unarchive"
              ? "Report unarchived."
              : "Report updated.",
      ),
  });
  const createTemplate = useMutation({
    mutationFn: async ({ title, kind }: { title: string; kind: string }) => {
      if (!editable || sections.length >= 30)
        throw new Error("Section creation unavailable");
      libraryWriting.current = true;
      return parseCreatedTemplate(
        (
          await api<{ data: unknown }>("/section-templates", {
            method: "POST",
            body: { title, kind },
          })
        ).data,
        title,
        kind,
      );
    },
    onSuccess: async (template) => {
      change([
        ...sections,
        newReportSection(
          template.title,
          template.kind,
          sections.length + 1,
          template,
        ),
      ]);
      setCustomTitle("");
      setSaveToLibrary(false);
      setNotice(
        "Section structure saved to the library and added to this draft. Save the report to persist its content.",
      );
      await cache.invalidateQueries({
        queryKey: ["configuration", "sections"],
      });
    },
    onSettled: () => {
      libraryWriting.current = false;
    },
  });
  const busy =
    save.isPending || transition.isPending || createTemplate.isPending;
  const change = (next: ReportSection[]) => {
    latestDraft.current = next;
    setDrafts(next);
    setNotice("");
    setInvalid(undefined);
    transition.reset();
    setIntent(null);
  };
  const { mutate: mutateSave } = save;
  const saveNow = useCallback(
    (manual = false) => {
      const snapshot = latestDraft.current;
      if (
        !snapshot ||
        !editable ||
        busy ||
        saving.current ||
        libraryWriting.current ||
        (!manual && autosavePaused)
      )
        return;
      try {
        sectionPayload(snapshot);
        setInvalid(undefined);
        saving.current = true;
        mutateSave(snapshot);
      } catch {
        setInvalid(
          "Check section titles, content limits and table dimensions before saving.",
        );
      }
    },
    [editable, busy, autosavePaused, mutateSave],
  );
  useEffect(() => {
    if (!dirty || !editable || busy || autosavePaused) return;
    const timer = setTimeout(() => saveNow(), 5000);
    return () => clearTimeout(timer);
  }, [drafts, dirty, editable, busy, autosavePaused, saveNow]);
  const choose = (action: Action) => {
    setIntent(action);
    transition.reset();
    setNotice("");
  };
  const move = (index: number, direction: number) => {
    const next = [...sections];
    const target = index + direction;
    if (index === 0 || target < 1 || target >= next.length) return;
    [next[index], next[target]] = [next[target]!, next[index]!];
    change(next);
  };
  return (
    <section>
      <h1>Session report</h1>
      <Pending active={query.isPending} />
      <Feedback error={query.error} />
      {query.isError && (
        <Button onClick={() => query.refetch()}>Try again</Button>
      )}
      {report && (
        <>
          <div className="my-5 rounded-xl border border-border p-5">
            <h2>
              {report.session.date} · {reportLabels[report.status]}
            </h2>
            <p>
              {report.academicYear} · {report.term.name}
            </p>
            <p>
              Author: {report.author.name} · Version {report.version}
            </p>
            <p>{report.openChangeRequests} open change requests</p>
            {editable && (
              <>
                <p role="status">
                  {save.isPending
                    ? "Saving report…"
                    : dirty
                      ? "Unsaved report changes"
                      : "Saved report content"}
                </p>
                {savedAt && !dirty && !save.isPending && (
                  <p>Saved at {savedAt}</p>
                )}
              </>
            )}
            {report.firstReadAt && (
              <p>First read: {report.firstReadAt.slice(0, 10)}</p>
            )}
            {report.archivedAt && <p>Archived — read only</p>}
          </div>
          {editable ? (
            <>
              <p className="mb-4 text-muted-foreground">
                Report content saves five seconds after editing stops and when a
                content field loses focus. You can also use Save report. Wait
                for saved confirmation before leaving. Failed saves keep your
                edits and pause autosave until you retry. Drafts are lost when
                navigating away.
              </p>
              <div
                className="grid gap-5"
                onBlur={(event) => {
                  if (
                    event.target instanceof HTMLInputElement ||
                    event.target instanceof HTMLTextAreaElement
                  ) {
                    if (
                      event.relatedTarget instanceof Element &&
                      event.relatedTarget.closest("button")
                    )
                      return;
                    saveNow();
                  }
                }}
              >
                {sections.map((section, index) => (
                  <article
                    key={editorKeys[section.id] ?? section.id}
                    className="min-w-0 rounded-xl border border-border p-5"
                  >
                    <h2>{section.title}</h2>
                    <p className="mb-3 text-sm">
                      {section.isMandatory
                        ? "Mandatory section"
                        : "Optional section"}
                    </p>
                    <ReportSectionEditor
                      section={section}
                      disabled={
                        transition.isPending || createTemplate.isPending
                      }
                      change={(next) =>
                        change(
                          sections.map((current) =>
                            current.id === section.id ? next : current,
                          ),
                        )
                      }
                    />
                    <div className="mt-4 flex flex-wrap gap-3">
                      <Button
                        variant="outline"
                        disabled={busy || index <= 1}
                        onClick={() => move(index, -1)}
                        aria-label={`Move up ${section.title}`}
                      >
                        Move up
                      </Button>
                      <Button
                        variant="outline"
                        disabled={
                          busy || index === 0 || index === sections.length - 1
                        }
                        onClick={() => move(index, 1)}
                        aria-label={`Move down ${section.title}`}
                      >
                        Move down
                      </Button>
                      {!section.isMandatory && (
                        <Button
                          variant="outline"
                          disabled={busy}
                          onClick={() =>
                            change(
                              sections.filter(
                                (current) => current.id !== section.id,
                              ),
                            )
                          }
                          aria-label={`Remove section ${section.title}`}
                        >
                          Remove section
                        </Button>
                      )}
                    </div>
                  </article>
                ))}
              </div>
              <ReportLibrary
                key={`${id}-${user.id}-${user.role}`}
                sections={sections}
                disabled={busy}
                add={(section) => change([...sections, section])}
              />
              <form
                className="my-5 grid gap-4 rounded-xl border border-border p-5"
                noValidate
                onSubmit={(event) => {
                  event.preventDefault();
                  if (
                    !customTitle.trim() ||
                    customTitle.trim().length > 120 ||
                    sections.length >= 30
                  ) {
                    setInvalid(
                      "Enter a title up to 120 characters; reports allow at most 30 sections.",
                    );
                    return;
                  }
                  setInvalid(undefined);
                  setNotice("");
                  createTemplate.reset();
                  if (saveToLibrary) {
                    createTemplate.mutate({
                      title: customTitle.trim(),
                      kind: customKind,
                    });
                  } else {
                    change([
                      ...sections,
                      newReportSection(
                        customTitle,
                        customKind,
                        sections.length + 1,
                      ),
                    ]);
                    setCustomTitle("");
                  }
                }}
              >
                <h2>Add a one-off section</h2>
                <Field id="custom-title" label="Section title">
                  <Input
                    id="custom-title"
                    maxLength={120}
                    value={customTitle}
                    disabled={transition.isPending || createTemplate.isPending}
                    onChange={(event) => setCustomTitle(event.target.value)}
                  />
                </Field>
                <Field id="custom-kind" label="Section kind">
                  <Select
                    id="custom-kind"
                    value={customKind}
                    disabled={transition.isPending || createTemplate.isPending}
                    onChange={(event) => setCustomKind(event.target.value)}
                  >
                    <option value="TEXT">Text</option>
                    <option value="BULLETS">Bullet list</option>
                    <option value="TABLE">Table</option>
                  </Select>
                </Field>
                <label className="flex min-h-11 items-center gap-3">
                  <input
                    type="checkbox"
                    checked={saveToLibrary}
                    disabled={transition.isPending || createTemplate.isPending}
                    onChange={(event) => {
                      setSaveToLibrary(event.target.checked);
                      createTemplate.reset();
                    }}
                  />
                  Save section structure to library
                </label>
                <p className="text-sm text-muted-foreground">
                  The library saves the title and section type, not report text.
                  New custom templates are available for selection in future
                  reports and are never preselected. Creating a library template
                  is separate from saving this report.
                </p>
                <Feedback error={createTemplate.error} />
                <Pending active={createTemplate.isPending} />
                <Button disabled={busy || sections.length >= 30}>
                  Add custom section
                </Button>
              </form>
              <details className="my-5 rounded-xl border border-border p-5">
                <summary>Preview current content</summary>
                <ReportDocument
                  report={report}
                  workingSections={sections}
                  unsaved={dirty}
                />
              </details>
              {autosavePaused && !save.isPending && (
                <p role="status">
                  Not saved — autosave is paused. Use Save report to retry. Your
                  edits are still here.
                </p>
              )}
              <div className="my-4 flex flex-wrap gap-3">
                <Button disabled={!dirty || busy} onClick={() => saveNow(true)}>
                  Save report
                </Button>
                <Button
                  variant="outline"
                  disabled={!dirty || busy}
                  onClick={() => {
                    clearDraft();
                    setInvalid(undefined);
                    save.reset();
                    setNotice("");
                  }}
                >
                  Discard unsaved edits
                </Button>
              </div>
            </>
          ) : (
            <ReportDocument report={report} />
          )}
          {dirty && !editable && (
            <div className="my-4 grid gap-3">
              <p>
                Your unsaved edits are retained in memory, but this report is no
                longer editable. Discard them before changing its state.
              </p>
              <Button
                variant="outline"
                disabled={busy}
                onClick={() => {
                  clearDraft();
                  setIntent(null);
                  save.reset();
                  setInvalid(undefined);
                }}
              >
                Discard unavailable draft edits
              </Button>
            </div>
          )}
          <ReportHistory
            key={`${id}-${user.id}-${user.role}`}
            report={report}
            blocked={dirty || busy}
          />
          <ReportFeedback report={report} />
          {invalid && (
            <p role="alert" className="field-error">
              {invalid}
            </p>
          )}
          <Feedback error={save.error || transition.error} />
          <Pending active={busy} />
          {notice && <p role="status">{notice}</p>}
          {user.role === "COORDINATOR" && !report.archivedAt && (
            <div className="my-5 flex flex-wrap gap-3">
              {report.author.id !== user.id ? (
                report.status === "DRAFT" && (
                  <Button disabled={busy} onClick={() => choose("takeover")}>
                    Take over report
                  </Button>
                )
              ) : (
                <>
                  {report.status === "DRAFT" ? (
                    <>
                      <Button
                        disabled={dirty || busy}
                        onClick={() => choose("confirm")}
                      >
                        Confirm report
                      </Button>
                      {report.sections.some(
                        (section) => section.key === "progress",
                      ) && (
                        <Button
                          variant="outline"
                          disabled={dirty || busy}
                          onClick={() => choose("progress")}
                        >
                          Refresh progress from session
                        </Button>
                      )}
                      {report.sections.some(
                        (section) => section.key === "highlights",
                      ) && (
                        <Button
                          variant="outline"
                          disabled={dirty || busy}
                          onClick={() => choose("highlights")}
                        >
                          Refresh highlights from session
                        </Button>
                      )}
                    </>
                  ) : (
                    <>
                      <Button
                        variant="outline"
                        disabled={busy}
                        onClick={() => choose("reopen")}
                      >
                        Reopen to edit
                      </Button>
                      {report.status === "FINAL" && (
                        <Button disabled={busy} onClick={() => choose("send")}>
                          Send to Sponsor
                        </Button>
                      )}
                    </>
                  )}
                </>
              )}
            </div>
          )}
          {user.role === "COORDINATOR" &&
            (report.archivedAt ||
              ["SENT", "CHANGES_REQUESTED"].includes(report.status)) && (
              <section
                className="my-5 grid gap-3 rounded-xl border border-border p-5"
                aria-labelledby="report-archive-heading"
              >
                <h2 id="report-archive-heading">Report archive</h2>
                <p>
                  {report.archivedAt
                    ? "This report is archived. Reading, sent history and Word downloads remain available."
                    : "Archive completed sent reports to keep the active list focused. Reports are retained, not deleted."}
                </p>
                {!report.archivedAt &&
                  !canReportAction(report, user, "archive") && (
                    <p>
                      Only sent reports without open change requests can be
                      archived. Resolve requests and finish any rework first.
                    </p>
                  )}
                <Button
                  variant="outline"
                  disabled={
                    dirty ||
                    busy ||
                    !canReportAction(
                      report,
                      user,
                      report.archivedAt ? "unarchive" : "archive",
                    )
                  }
                  onClick={() =>
                    choose(report.archivedAt ? "unarchive" : "archive")
                  }
                >
                  {report.archivedAt ? "Unarchive report" : "Archive report"}
                </Button>
              </section>
            )}
          {intent && canReportAction(report, user, intent) && (
            <div
              role="group"
              aria-label={actionCopy[intent].title}
              className="my-5 grid gap-3 rounded-xl border border-border p-5"
            >
              <h2>{actionCopy[intent].title}</h2>
              <p>{actionCopy[intent].description}</p>
              <div className="flex flex-wrap gap-3">
                <Button
                  disabled={busy || dirty}
                  onClick={() => transition.mutate(intent)}
                >
                  {actionCopy[intent].confirm}
                </Button>
                <Button
                  variant="outline"
                  disabled={busy}
                  onClick={() => setIntent(null)}
                >
                  Back to report
                </Button>
              </div>
            </div>
          )}
        </>
      )}
    </section>
  );
}
