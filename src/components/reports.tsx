export function SessionReport({
  session,
  disabled,
}: {
  session: SessionRecord;
  disabled: boolean;
}) {
  const user = useSession(),
    cache = useQueryClient(),
    router = useRouter();
  const [created, setCreated] = useState(false);
  const mutation = useMutation({
    mutationFn: async () => {
      const report = parseReport(
        (
          await api<{ data: unknown }>(`/sessions/${session.id}/report`, {
            method: "POST",
            body: {},
          })
        ).data,
        user.role,
      );
      if (report.session.id !== session.id || report.author.id !== user.id)
        throw new Error("Unexpected report acknowledgement");
      return report;
    },
    onSuccess: async (report) => {
      setCreated(true);
      router.push(`/reports/${report.id}`);
      await cache.invalidateQueries({ queryKey: ["sessions"] });
      await cache.invalidateQueries({ queryKey: ["reports"] });
    },
  });
  return (
    <section className="my-5 grid gap-3 rounded-xl border border-border p-5">
      <h2>Session report</h2>
      {session.report ? (
        <Link className="underline" href={`/reports/${session.report.id}`}>
          Open report
        </Link>
      ) : session.status !== "HELD" ? (
        <p>Cancelled sessions cannot have reports.</p>
      ) : session.createdBy.id !== user.id ? (
        <p>The session creator must create its initial report.</p>
      ) : (
        <>
          <p>
            Start with the mandatory and preselected sections generated by the
            server. Save session and entry changes first.
          </p>
          <Button
            disabled={disabled || mutation.isPending || created}
            onClick={() => mutation.mutate()}
          >
            Create report
          </Button>
          <Feedback error={mutation.error} />
          <Pending active={mutation.isPending} />
          <Button
            variant="outline"
            disabled={mutation.isPending}
            onClick={() => cache.invalidateQueries({ queryKey: ["sessions"] })}
          >
            Refresh report availability
          </Button>
        </>
      )}
    </section>
  );
}
export function Reports() {
  const user = useSession(),
    [page, setPage] = useState(1),
    [status, setStatus] = useState(""),
    [archived, setArchived] = useState(false),
    [search, setSearch] = useState(""),
    [q, setQ] = useState("");
  const query = useQuery({
    queryKey: [
      "reports",
      "list",
      user.id,
      user.role,
      page,
      status,
      archived,
      q,
    ],
    queryFn: async () => {
      const params = new URLSearchParams({
        page: String(page),
        pageSize: "20",
        archived: String(archived),
      });
      if (status) params.set("status", status);
      if (q) params.set("q", q);
      return parseReportPage(await api(`/reports?${params}`), user.role);
    },
  });
  return (
    <section>
      <h1>Reports</h1>
      <p className="mb-5 text-muted-foreground">
        {user.role === "SPONSOR"
          ? "Read the latest sent report snapshots. Work in progress stays private."
          : "Create reports from held sessions. Only the author can edit and deliver them."}
      </p>
      <form
        className="my-4 flex flex-wrap items-end gap-3"
        onSubmit={(event) => {
          event.preventDefault();
          setQ(search.trim());
          setPage(1);
        }}
      >
        <div className="min-w-0 flex-1">
          <Field
            id="report-search"
            label={
              user.role === "SPONSOR"
                ? "Search sent reports"
                : "Search academic year"
            }
          >
            <Input
              id="report-search"
              value={search}
              maxLength={100}
              onChange={(event) => setSearch(event.target.value)}
            />
          </Field>
        </div>
        <Button>Search reports</Button>
      </form>
      <Field id="report-status" label="Report status">
        <Select
          id="report-status"
          value={status}
          onChange={(event) => {
            setStatus(event.target.value);
            setPage(1);
          }}
        >
          <option value="">All permitted reports</option>
          {Object.entries(reportLabels)
            .filter(
              ([key]) =>
                user.role !== "SPONSOR" ||
                ["SENT", "CHANGES_REQUESTED"].includes(key),
            )
            .map(([key, label]) => (
              <option key={key} value={key}>
                {label}
              </option>
            ))}
        </Select>
      </Field>
      <label className="my-4 flex min-h-11 items-center gap-3">
        <input
          type="checkbox"
          checked={archived}
          onChange={(event) => {
            setArchived(event.target.checked);
            setPage(1);
          }}
        />
        Archived reports
      </label>
      <Pending active={query.isPending} />
      <Feedback error={query.error} />
      {query.isError && (
        <Button onClick={() => query.refetch()}>Try again</Button>
      )}
      {query.data && (
        <>
          <div className="my-6 grid gap-4 sm:grid-cols-2">
            {query.data.data.length ? (
              query.data.data.map((report) => (
                <article
                  key={report.id}
                  className="min-w-0 break-words rounded-xl border border-border p-5"
                >
                  <h2>
                    <Link className="underline" href={`/reports/${report.id}`}>
                      {report.session.date} report
                    </Link>
                  </h2>
                  <p>
                    {report.academicYear} · {report.term.name}
                  </p>
                  <p>
                    {reportLabels[report.status]} · Version {report.version}
                  </p>
                  <p>Author: {report.author.name}</p>
                  {report.status === "SENT" &&
                    report.openChangeRequests === 0 && <p>Approved</p>}
                  <p>{report.openChangeRequests} open change requests</p>
                </article>
              ))
            ) : (
              <p>No matching reports.</p>
            )}
          </div>
          <div className="flex flex-wrap items-center gap-3">
            <Button
              variant="outline"
              disabled={page <= 1 || query.isFetching}
              onClick={() => setPage((value) => value - 1)}
            >
              Previous reports
            </Button>
            <p>
              Report page {page} of {Math.max(1, query.data.meta.totalPages)}
            </p>
            <Button
              variant="outline"
              disabled={page >= query.data.meta.totalPages || query.isFetching}
              onClick={() => setPage((value) => value + 1)}
            >
              Next reports
            </Button>
          </div>
        </>
      )}
    </section>
  );
}
