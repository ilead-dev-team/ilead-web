"use client";
import Link from "next/link";
import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { api } from "@/lib/api";
import {
  parseReport,
  canReportAction,
  parseReportPage,
  sectionPayload,
  reportLabels,
  type Report,
  type ReportSection,
} from "@/lib/reports";
import type { SessionRecord } from "@/lib/sessions";
import { useSession } from "./session";
import { Button } from "./ui/button";
import { Field, Input, Select } from "./ui/field";
import { Feedback, Pending } from "./account/feedback";
import { ReportContent } from "./report-content";
import { ReportSectionEditor } from "./report-section-editor";

export function SessionReport({
  session,
  disabled,
}: {
  session: SessionRecord;
  disabled: boolean;
}) {
  const user = useSession(),
    cache = useQueryClient(),
    router = useRouter();
  const [created, setCreated] = useState(false);
  const mutation = useMutation({
    mutationFn: async () => {
      const report = parseReport(
        (
          await api<{ data: unknown }>(`/sessions/${session.id}/report`, {
            method: "POST",
            body: {},
          })
        ).data,
        user.role,
      );
      if (report.session.id !== session.id || report.author.id !== user.id)
        throw new Error("Unexpected report acknowledgement");
      return report;
    },
    onSuccess: async (report) => {
      setCreated(true);
      router.push(`/reports/${report.id}`);
      await cache.invalidateQueries({ queryKey: ["sessions"] });
      await cache.invalidateQueries({ queryKey: ["reports"] });
    },
  });
  return (
    <section className="my-5 grid gap-3 rounded-xl border border-border p-5">
      <h2>Session report</h2>
      {session.report ? (
        <Link className="underline" href={`/reports/${session.report.id}`}>
          Open report
        </Link>
      ) : session.status !== "HELD" ? (
        <p>Cancelled sessions cannot have reports.</p>
      ) : session.createdBy.id !== user.id ? (
        <p>The session creator must create its initial report.</p>
      ) : (
        <>
          <p>
            Start with the mandatory and preselected sections generated by the
            server. Save session and entry changes first.
          </p>
          <Button
            disabled={disabled || mutation.isPending || created}
            onClick={() => mutation.mutate()}
          >
            Create report
          </Button>
          <Feedback error={mutation.error} />
          <Pending active={mutation.isPending} />
          <Button
            variant="outline"
            disabled={mutation.isPending}
            onClick={() => cache.invalidateQueries({ queryKey: ["sessions"] })}
          >
            Refresh report availability
          </Button>
        </>
      )}
    </section>
  );
}
export function Reports() {
  const user = useSession(),
    [page, setPage] = useState(1),
    [status, setStatus] = useState(""),
    [archived, setArchived] = useState(false),
    [search, setSearch] = useState(""),
    [q, setQ] = useState("");
  const query = useQuery({
    queryKey: [
      "reports",
      "list",
      user.id,
      user.role,
      page,
      status,
      archived,
      q,
    ],
    queryFn: async () => {
      const params = new URLSearchParams({
        page: String(page),
        pageSize: "20",
        archived: String(archived),
      });
      if (status) params.set("status", status);
      if (q) params.set("q", q);
      return parseReportPage(await api(`/reports?${params}`), user.role);
    },
  });
  return (
    <section>
      <h1>Reports</h1>
      <p className="mb-5 text-muted-foreground">
        {user.role === "SPONSOR"
          ? "Read the latest sent report snapshots. Work in progress stays private."
          : "Create reports from held sessions. Only the author can edit and deliver them."}
      </p>
      <form
        className="my-4 flex flex-wrap items-end gap-3"
        onSubmit={(event) => {
          event.preventDefault();
          setQ(search.trim());
          setPage(1);
        }}
      >
        <div className="min-w-0 flex-1">
          <Field
            id="report-search"
            label={
              user.role === "SPONSOR"
                ? "Search sent reports"
                : "Search academic year"
            }
          >
            <Input
              id="report-search"
              value={search}
              maxLength={100}
              onChange={(event) => setSearch(event.target.value)}
            />
          </Field>
        </div>
        <Button>Search reports</Button>
      </form>
      <Field id="report-status" label="Report status">
        <Select
          id="report-status"
          value={status}
          onChange={(event) => {
            setStatus(event.target.value);
            setPage(1);
          }}
        >
          <option value="">All permitted reports</option>
          {Object.entries(reportLabels)
            .filter(
              ([key]) =>
                user.role !== "SPONSOR" ||
                ["SENT", "CHANGES_REQUESTED"].includes(key),
            )
            .map(([key, label]) => (
              <option key={key} value={key}>
                {label}
              </option>
            ))}
        </Select>
      </Field>
      <label className="my-4 flex min-h-11 items-center gap-3">
        <input
          type="checkbox"
          checked={archived}
          onChange={(event) => {
            setArchived(event.target.checked);
            setPage(1);
          }}
        />
        Archived reports
      </label>
      <Pending active={query.isPending} />
      <Feedback error={query.error} />
      {query.isError && (
        <Button onClick={() => query.refetch()}>Try again</Button>
      )}
      {query.data && (
        <>
          <div className="my-6 grid gap-4 sm:grid-cols-2">
            {query.data.data.length ? (
              query.data.data.map((report) => (
                <article
                  key={report.id}
                  className="min-w-0 break-words rounded-xl border border-border p-5"
                >
                  <h2>
                    <Link className="underline" href={`/reports/${report.id}`}>
                      {report.session.date} report
                    </Link>
                  </h2>
                  <p>
                    {report.academicYear} · {report.term.name}
                  </p>
                  <p>
                    {reportLabels[report.status]} · Version {report.version}
                  </p>
                  <p>Author: {report.author.name}</p>
                  {report.status === "SENT" &&
                    report.openChangeRequests === 0 && <p>Approved</p>}
                  <p>{report.openChangeRequests} open change requests</p>
                </article>
              ))
            ) : (
              <p>No matching reports.</p>
            )}
          </div>
          <div className="flex flex-wrap items-center gap-3">
            <Button
              variant="outline"
              disabled={page <= 1 || query.isFetching}
              onClick={() => setPage((value) => value - 1)}
            >
              Previous reports
            </Button>
            <p>
              Report page {page} of {Math.max(1, query.data.meta.totalPages)}
            </p>
            <Button
              variant="outline"
              disabled={page >= query.data.meta.totalPages || query.isFetching}
              onClick={() => setPage((value) => value + 1)}
            >
              Next reports
            </Button>
          </div>
        </>
      )}
    </section>
  );
}
type Action =
  "confirm" | "reopen" | "send" | "takeover" | "progress" | "highlights";
const actionCopy: Record<
  Action,
  { title: string; confirm: string; description: string }
> = {
  confirm: {
    title: "Confirm report",
    confirm: "Confirm report now",
    description:
      "This locks the saved draft as Final. Save every edit before confirming.",
  },
  reopen: {
    title: "Reopen to edit",
    confirm: "Reopen report",
    description:
      "This creates a draft for editing. Sponsors keep the last sent snapshot during rework.",
  },
  send: {
    title: "Send to Sponsor",
    confirm: "Confirm sending",
    description:
      "This publishes the saved Final report, stores an immutable version and notifies Sponsors.",
  },
  takeover: {
    title: "Take over report",
    confirm: "Confirm takeover",
    description:
      "This transfers draft authorship and report reminders to you and notifies the former author.",
  },
  progress: {
    title: "Refresh progress from session",
    confirm: "Replace progress from session",
    description:
      "This replaces the saved progress table with current session entries. Save other edits first.",
  },
  highlights: {
    title: "Refresh highlights from session",
    confirm: "Replace highlights from session",
    description:
      "This replaces the saved highlights with generated activities, including any sentences you previously edited.",
  },
};
export function ReportDetail({ id }: { id: string }) {
  const user = useSession(),
    cache = useQueryClient();
  const key = ["reports", "detail", user.id, user.role, id];
  const [drafts, setDrafts] = useState<ReportSection[] | null>(null),
    [invalid, setInvalid] = useState<string>(),
    [notice, setNotice] = useState(""),
    [intent, setIntent] = useState<Action | null>(null),
    [customTitle, setCustomTitle] = useState(""),
    [customKind, setCustomKind] = useState("TEXT");
  const query = useQuery({
    queryKey: key,
    staleTime: 0,
    queryFn: async () => {
      const report = parseReport(
        (await api<{ data: unknown }>(`/reports/${id}`)).data,
        user.role,
      );
      if (report.id !== id) throw new Error("Unexpected report");
      return report;
    },
  });
  const report = query.data,
    dirty = drafts !== null;
  const editable =
    report &&
    user.role === "COORDINATOR" &&
    report.author.id === user.id &&
    report.status === "DRAFT" &&
    !report.archivedAt;
  const sections = drafts ?? report?.sections ?? [];
  useEffect(() => {
    if (!dirty) return;
    const warn = (event: BeforeUnloadEvent) => {
      event.preventDefault();
      event.returnValue = "";
    };
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);
  const accept = async (result: Report, message: string) => {
    cache.setQueryData(key, result);
    setDrafts(null);
    setIntent(null);
    setNotice(message);
    await cache.invalidateQueries({ queryKey: ["reports", "list"] });
    await cache.invalidateQueries({ queryKey: ["sessions"] });
  };
  const save = useMutation({
    mutationFn: async () => {
      const result = parseReport(
        (
          await api<{ data: unknown }>(`/reports/${id}/sections`, {
            method: "PATCH",
            body: sectionPayload(sections),
          })
        ).data,
        user.role,
      );
      if (result.id !== id || result.status !== "DRAFT")
        throw new Error("Unexpected save acknowledgement");
      return result;
    },
    onSuccess: (result) => accept(result, "Report saved."),
  });
  const transition = useMutation({
    mutationFn: async (action: Action) => {
      if (!report || !canReportAction(report, user, action))
        throw new Error("This report action is no longer available.");
      const regenerate = action === "progress" || action === "highlights";
      const result = parseReport(
        (
          await api<{ data: unknown }>(
            `/reports/${id}/${regenerate ? "sections/regenerate" : action}`,
            { method: "POST", body: regenerate ? { key: action } : {} },
          )
        ).data,
        user.role,
      );
      const expected =
        action === "confirm" ? "FINAL" : action === "send" ? "SENT" : "DRAFT";
      if (
        result.id !== id ||
        result.status !== expected ||
        (action === "takeover" && result.author.id !== user.id)
      )
        throw new Error("Unexpected report acknowledgement");
      return result;
    },
    onSuccess: (result, action) =>
      accept(
        result,
        action === "send" ? "Report sent to Sponsors." : "Report updated.",
      ),
  });
  const busy = save.isPending || transition.isPending;
  const change = (next: ReportSection[]) => {
    setDrafts(next);
    setNotice("");
    setInvalid(undefined);
    save.reset();
    transition.reset();
    setIntent(null);
  };
  const choose = (action: Action) => {
    setIntent(action);
    transition.reset();
    setNotice("");
  };
  const move = (index: number, direction: number) => {
    const next = [...sections];
    const target = index + direction;
    if (index === 0 || target < 1 || target >= next.length) return;
    [next[index], next[target]] = [next[target]!, next[index]!];
    change(next);
  };
  return (
    <section>
      <h1>Session report</h1>
      <Pending active={query.isPending} />
      <Feedback error={query.error} />
      {query.isError && (
        <Button onClick={() => query.refetch()}>Try again</Button>
      )}
      {report && (
        <>
          <div className="my-5 rounded-xl border border-border p-5">
            <h2>
              {report.session.date} · {reportLabels[report.status]}
            </h2>
            <p>
              {report.academicYear} · {report.term.name}
            </p>
            <p>
              Author: {report.author.name} · Version {report.version}
            </p>
            <p>{report.openChangeRequests} open change requests</p>
            {report.firstReadAt && (
              <p>First read: {report.firstReadAt.slice(0, 10)}</p>
            )}
            {report.archivedAt && <p>Archived — read only</p>}
          </div>
          {editable ? (
            <>
              <p className="mb-4 text-muted-foreground">
                Save explicitly before confirming or leaving this page. Unsaved
                edits stay after failures but are lost when navigating away.
                Automatic saving is not available yet.
              </p>
              <div className="grid gap-5">
                {sections.map((section, index) => (
                  <article
                    key={section.id}
                    className="min-w-0 rounded-xl border border-border p-5"
                  >
                    <h2>{section.title}</h2>
                    <p className="mb-3 text-sm">
                      {section.isMandatory
                        ? "Mandatory section"
                        : "Optional section"}
                    </p>
                    <ReportSectionEditor
                      section={section}
                      disabled={busy}
                      change={(next) =>
                        change(
                          sections.map((current) =>
                            current.id === section.id ? next : current,
                          ),
                        )
                      }
                    />
                    <div className="mt-4 flex flex-wrap gap-3">
                      <Button
                        variant="outline"
                        disabled={busy || index <= 1}
                        onClick={() => move(index, -1)}
                        aria-label={`Move up ${section.title}`}
                      >
                        Move up
                      </Button>
                      <Button
                        variant="outline"
                        disabled={
                          busy || index === 0 || index === sections.length - 1
                        }
                        onClick={() => move(index, 1)}
                        aria-label={`Move down ${section.title}`}
                      >
                        Move down
                      </Button>
                      {!section.isMandatory && (
                        <Button
                          variant="outline"
                          disabled={busy}
                          onClick={() =>
                            change(
                              sections.filter(
                                (current) => current.id !== section.id,
                              ),
                            )
                          }
                          aria-label={`Remove section ${section.title}`}
                        >
                          Remove section
                        </Button>
                      )}
                    </div>
                  </article>
                ))}
              </div>
              <form
                className="my-5 grid gap-4 rounded-xl border border-border p-5"
                noValidate
                onSubmit={(event) => {
                  event.preventDefault();
                  if (
                    !customTitle.trim() ||
                    customTitle.trim().length > 120 ||
                    sections.length >= 30
                  ) {
                    setInvalid(
                      "Enter a title up to 120 characters; reports allow at most 30 sections.",
                    );
                    return;
                  }
                  const base = {
                    id: `new-${crypto.randomUUID()}`,
                    key: null,
                    title: customTitle.trim(),
                    isMandatory: false,
                    autoSource: "NONE" as const,
                    position: sections.length + 1,
                  };
                  const section: ReportSection =
                    customKind === "BULLETS"
                      ? { ...base, kind: "BULLETS", content: { items: [] } }
                      : customKind === "TABLE"
                        ? {
                            ...base,
                            kind: "TABLE",
                            content: { columns: ["Column"], rows: [] },
                          }
                        : { ...base, kind: "TEXT", content: { text: "" } };
                  change([...sections, section]);
                  setCustomTitle("");
                }}
              >
                <h2>Add a one-off section</h2>
                <Field id="custom-title" label="Section title">
                  <Input
                    id="custom-title"
                    maxLength={120}
                    value={customTitle}
                    disabled={busy}
                    onChange={(event) => setCustomTitle(event.target.value)}
                  />
                </Field>
                <Field id="custom-kind" label="Section kind">
                  <Select
                    id="custom-kind"
                    value={customKind}
                    disabled={busy}
                    onChange={(event) => setCustomKind(event.target.value)}
                  >
                    <option value="TEXT">Text</option>
                    <option value="BULLETS">Bullet list</option>
                    <option value="TABLE">Table</option>
                  </Select>
                </Field>
                <Button disabled={busy || sections.length >= 30}>
                  Add custom section
                </Button>
              </form>
              <details className="my-5 rounded-xl border border-border p-5">
                <summary>Preview current content</summary>
                <ReportContent sections={sections} />
              </details>
              <p role="status">
                {dirty ? "Unsaved report changes" : "Saved report content"}
              </p>
              <div className="my-4 flex flex-wrap gap-3">
                <Button
                  disabled={!dirty || busy}
                  onClick={() => {
                    try {
                      sectionPayload(sections);
                      setInvalid(undefined);
                      save.mutate();
                    } catch {
                      setInvalid(
                        "Check section titles, content limits and table dimensions before saving.",
                      );
                    }
                  }}
                >
                  Save report
                </Button>
                <Button
                  variant="outline"
                  disabled={!dirty || busy}
                  onClick={() => {
                    setDrafts(null);
                    setInvalid(undefined);
                    save.reset();
                    setNotice("");
                  }}
                >
                  Discard unsaved edits
                </Button>
              </div>
            </>
          ) : (
            <ReportContent sections={report.sections} />
          )}
          {dirty && !editable && (
            <div className="my-4 grid gap-3">
              <p>
                Your unsaved edits are retained in memory, but this report is no
                longer editable. Discard them before changing its state.
              </p>
              <Button
                variant="outline"
                disabled={busy}
                onClick={() => {
                  setDrafts(null);
                  setIntent(null);
                  save.reset();
                  setInvalid(undefined);
                }}
              >
                Discard unavailable draft edits
              </Button>
            </div>
          )}
          {invalid && (
            <p role="alert" className="field-error">
              {invalid}
            </p>
          )}
          <Feedback error={save.error || transition.error} />
          <Pending active={busy} />
          {notice && <p role="status">{notice}</p>}
          {user.role === "COORDINATOR" && !report.archivedAt && (
            <div className="my-5 flex flex-wrap gap-3">
              {report.author.id !== user.id ? (
                report.status === "DRAFT" && (
                  <Button disabled={busy} onClick={() => choose("takeover")}>
                    Take over report
                  </Button>
                )
              ) : (
                <>
                  {report.status === "DRAFT" ? (
                    <>
                      <Button
                        disabled={dirty || busy}
                        onClick={() => choose("confirm")}
                      >
                        Confirm report
                      </Button>
                      {report.sections.some(
                        (section) => section.key === "progress",
                      ) && (
                        <Button
                          variant="outline"
                          disabled={dirty || busy}
                          onClick={() => choose("progress")}
                        >
                          Refresh progress from session
                        </Button>
                      )}
                      {report.sections.some(
                        (section) => section.key === "highlights",
                      ) && (
                        <Button
                          variant="outline"
                          disabled={dirty || busy}
                          onClick={() => choose("highlights")}
                        >
                          Refresh highlights from session
                        </Button>
                      )}
                    </>
                  ) : (
                    <>
                      <Button
                        variant="outline"
                        disabled={busy}
                        onClick={() => choose("reopen")}
                      >
                        Reopen to edit
                      </Button>
                      {report.status === "FINAL" && (
                        <Button disabled={busy} onClick={() => choose("send")}>
                          Send to Sponsor
                        </Button>
                      )}
                    </>
                  )}
                </>
              )}
            </div>
          )}
          {intent && canReportAction(report, user, intent) && (
            <div
              role="group"
              aria-label={actionCopy[intent].title}
              className="my-5 grid gap-3 rounded-xl border border-border p-5"
            >
              <h2>{actionCopy[intent].title}</h2>
              <p>{actionCopy[intent].description}</p>
              <div className="flex flex-wrap gap-3">
                <Button
                  disabled={busy || dirty}
                  onClick={() => transition.mutate(intent)}
                >
                  {actionCopy[intent].confirm}
                </Button>
                <Button
                  variant="outline"
                  disabled={busy}
                  onClick={() => setIntent(null)}
                >
                  Back to report
                </Button>
              </div>
            </div>
          )}
        </>
      )}
    </section>
  );
}
